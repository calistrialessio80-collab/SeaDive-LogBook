function lifeWorms(la) {
  return `https://www.marinespecies.org/aphia.php?p=taxlist&searchPar=scientific&tName=${encodeURIComponent(la)}`;
}

function lifeNorm(s) {
  return String(s || "")
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "");
}

function lifeId(la) {
  return lifeNorm(la)
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

function sp(group, it, la, where, tag, size, depth, habitat, look, life, dive) {
  return { id: lifeId(la), group, it, la, where, tag, size, depth, habitat, look, life, dive };
}

