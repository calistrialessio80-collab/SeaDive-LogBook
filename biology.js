const LIFE_PHOTO_PATTERNS = {
  bande: ["banda", "bande", "strisc", "fascia", "fasce"],
  macchie: ["macchi", "puntin", "ocell"],
};

function lifeLookWords(x) {
  return lifeNorm(`${x.look} ${x.tag} ${x.life}`).split(/[^a-z]+/).filter((word) => word.length > 2);
}

function lifeWordHit(words, keys) {
  return keys.some((key) => words.some((word) => word === key || word.startsWith(key)));
}

function matchMarineLifeByPhoto(signals, group, where) {
  const colors = Array.isArray(signals?.colors) ? signals.colors : [];
  const patterns = Array.isArray(signals?.patterns) ? signals.patterns : [];
  const ranked = [];
  filterMarineLife("", group, where).forEach((x) => {
    const words = lifeLookWords(x);
    let score = 0;
    colors.forEach((color, index) => {
      const keys = LIFE_PHOTO_COLORS[color];
      if (keys && lifeWordHit(words, keys)) score += index === 0 ? 4 : 2;
    });
    patterns.forEach((pattern) => {
      const keys = LIFE_PHOTO_PATTERNS[pattern];
      if (keys && lifeWordHit(words, keys)) score += 3;
    });
    if (score > 0) ranked.push({ x, score });
  });
  ranked.sort((a, b) => b.score - a.score || a.x.it.localeCompare(b.x.it, "it"));
  return ranked.slice(0, 24).map((row) => row.x);
}

function lifeEmoji(x) {
  return lifeSection(x.group)?.emoji || "🌊";
}

const lifePageCache = {};

async function lifeInat(la) {
  for (const extra of ["&rank=species", ""]) {
    try {
      const res = await fetch(`https://api.inaturalist.org/v1/taxa?q=${encodeURIComponent(la)}${extra}`);
      if (!res.ok) continue;
      const data = await res.json();
      const photo = data.results?.[0]?.default_photo;
      const src = photo?.medium_url || photo?.square_url || photo?.url || "";
      if (src) return src;
    } catch {
      return "";
    }
  }
  return "";
}

async function lifePage(la, it) {
  const key = String(la || it || "");
  if (Object.prototype.hasOwnProperty.call(lifePageCache, key)) return lifePageCache[key];
  const empty = { extract: "", thumb: "", url: "", desc: "" };
  const titles = [la, it].filter(Boolean);
  for (const wiki of ["it", "en"]) {
    for (const title of titles) {
      try {
        const res = await fetch(
          `https://${wiki}.wikipedia.org/api/rest_v1/page/summary/${encodeURIComponent(String(title).replace(/ /g, "_"))}`
        );
        if (!res.ok) continue;
        const data = await res.json();
        if (data.type === "disambiguation") continue;
        const extract = data.extract || "";
        const thumb = data.thumbnail?.source || "";
        if (!extract && !thumb) continue;
        const page = {
          extract,
          thumb,
          url: data.content_urls?.desktop?.page || "",
          desc: data.description || "",
        };
        if (!page.thumb) page.thumb = await lifeInat(la);
        lifePageCache[key] = page;
        return page;
      } catch {
        /* prova il titolo successivo */
      }
    }
  }
  empty.thumb = await lifeInat(la);
  lifePageCache[key] = empty;
  return empty;
}

async function lifeThumb(la, it) {
  const page = await lifePage(la, it);
  return page.thumb || "";
}

